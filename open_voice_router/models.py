# Words seeded into every fresh install's vocabulary dictionary.
# STT engines frequently mis-transcribe these — they're high-value defaults
# without being so obscure that they'd hurt confidence on normal speech.
DEFAULT_WORD_DICTIONARY: list[str] = [
    "LinkedIn",   # "linked in" / "Linked In"
    "GitHub",     # "get hub" / "git hub"
    "ChatGPT",    # "chat GBT" / "chat G P T"
]


@dataclass
class ProviderConfig:
    """Configuration for a single STT or LLM provider."""

    id: str  # UUID
    name: str
    base_url: str  # validated HTTPS URL
    model: str
    quota_limit: int | None  # None = unlimited
    quota_used_today: int = 0
    system_prompt: str | None = None  # LLM only
    # "cloud" = officially-supported SaaS endpoint (Deepgram, Gemini, etc.)
    # "custom" = user-hosted or OpenAI-compatible endpoint (Ollama, LM Studio, etc.)
    kind: Literal["cloud", "custom"] = "cloud"
    enabled: bool = True  # Whether this provider participates in routing


@dataclass(frozen=True)
class WordTiming:
    """A single transcribed word with chunk-relative timing in seconds."""

    word: str
    start: float
    end: float

    @property
    def midpoint(self) -> float:
        return (self.start + self.end) / 2.0


@dataclass(frozen=True)
class LLMResult:
    """Structured LLM reply: the text plus live usage/limit signals.

    ``total_tokens`` comes from the OpenAI-standard ``usage`` block;
    ``remaining_requests`` / ``remaining_tokens`` come from the provider's
    ``x-ratelimit-remaining-*`` headers (None when not sent). These feed the
    smart-rotation tracker so it learns each provider's real headroom.
    """

    text: str
    total_tokens: int | None = None
    remaining_requests: int | None = None
    remaining_tokens: int | None = None


@dataclass(frozen=True)
class TranscriptionResult:
    """Normalized STT result returned by every provider adapter.

    ``words`` is the optional word-level timing list (chunk-relative seconds).
    Providers/models without word timestamps return ``words=None``; the
    transcript assembler then falls back to text-based overlap merging.
    """

    text: str
    words: tuple[WordTiming, ...] | None = None

    @property
    def has_word_timings(self) -> bool:
        return bool(self.words)


@dataclass
class PromptConfig:
    """A named reusable system prompt for the processing layer."""

    id: str  # UUID
    name: str  # e.g. "Email", "Coding", "Clean up"
    text: str  # The full prompt text
    is_active: bool = False  # Whether this is the currently selected prompt


@dataclass
class AppSettings:
    """Top-level application settings."""

    active_mode: Literal["dictation", "voice_to_ai"]
    hotkey: str  # Ctrl+Shift+Space → dictation
    microphone_device_id: int | None
    stt_providers: list[ProviderConfig]
    llm_providers: list[ProviderConfig]
    log_file_path: str
    hotkey_ai: str = "ctrl+shift+enter"    # Ctrl+Shift+Enter → voice-to-AI
    hotkey_grain: str = "ctrl+shift+g"    # Ctrl+Shift+G → Grain Assist (select text → instruct LLM)
    # Ctrl+Shift+Z → start a non-real-time (record-then-transcribe) session.
    # Real-time vs. batch is chosen by WHICH start key is used: this key always
    # records the whole take and transcribes it in one shot, while the normal
    # dictation key streams live. Like the other hotkeys, the output destination
    # (raw paste vs. LLM) is decided by which hotkey STOPS the session — stop
    # with this key for raw text, or with the AI key to send it to the LLM.
    hotkey_batch: str = "ctrl+shift+z"
    # Prompt-profile navigation while recording in Voice-to-AI mode. These cycle
    # the active prompt (models.AppSettings.prompts) backward / forward so the
    # user can pick "Email", "Code", etc. mid-sentence — the active prompt is
    # resolved at LLM-dispatch time, so switching takes effect for that session.
    hotkey_prompt_prev: str = "alt+left"
    hotkey_prompt_next: str = "alt+right"
    close_to_tray: bool = True             # False → closing window quits the app
    global_system_prompt: str = field(default_factory=lambda: DEFAULT_SYSTEM_PROMPT)
    prompts: list[PromptConfig] = field(default_factory=list)
    word_dictionary: list[str] = field(default_factory=lambda: list(DEFAULT_WORD_DICTIONARY))
    launch_on_boot: bool = False
    start_minimized: bool = True   # True = start silently in tray; False = open console on launch
    play_sound: bool = True
    process_audio: bool = True
    # Model_Load timeout in seconds; valid range [10, 120], default 30 (R7.2).
    local_stt_load_timeout_s: int = 30
    # Auto-unload idle policy in milliseconds. -1 = Never (keep loaded until
    # quit), 0 = Instant (unload right after each session), positive = unload
    # after that many ms of idle. Enforced by the backend so it works headless.
    local_stt_unload_idle_ms: int = 300_000  # default: 5 minutes
    # Load-on-startup: when True, the selected local model is pre-loaded at app
    # launch so the first dictation is instant instead of paying the cold
    # Model_Load latency. Unloading still follows local_stt_unload_idle_ms.
    # Off by default so a fresh install pays no idle RAM until the user opts in.
    local_stt_load_on_startup: bool = False
    # Selected local STT model — a registry id from
    # open_voice_router/local_asr/registry.py. Unknown ids resolve to the
    # registry default at load time, so a stale value degrades gracefully.
    # (Literal default mirrors registry.DEFAULT_MODEL_ID; kept literal so this
    # module stays import-light.)
    local_stt_model_id: str = "parakeet-tdt-0.6b-v3"
    # Rolling-window duration (seconds) for the real-time path: how much audio
    # accumulates before a chunk is cut and sent to the local model. Larger =
    # fewer chunk boundaries (more accurate) but a longer flush on stop. Valid
    # range [15, 60], default 20. Read per session by ChunkedAudioService.
    rolling_window_s: int = 20
    # Smart Rotation: when True, routing picks from ALL enabled cloud STT
    # providers in round-robin order. When False, only the single enabled
    # provider (local or cloud) is used.
    stt_smart_rotation: bool = False
    # Smart Rotation for LLM: when True, routing round-robins across all
    # enabled LLM providers. When False, only the single enabled provider is used.
    llm_smart_rotation: bool = False
    # Grain Assist provider — the LLM provider id the agent workflow uses.
    # Empty = auto (first enabled provider). Independent of the processing
    # rotation's enabled flags: an explicit choice is honoured even if that
    # provider is not enabled for dictation processing.
    grain_assist_provider_id: str = ""
    # Console panel appearance — False = light (default), True = dark. Persisted
    # so the user's light/dark choice survives restarts.
    ui_dark_mode: bool = False
    # UI history ring buffers — persisted so they survive restarts (max 10 each).
    transcription_history: list[dict] = field(default_factory=list)
    processing_history: list[dict] = field(default_factory=list)

    @staticmethod
    def defaults() -> "AppSettings":
        """Return a fresh AppSettings populated with sensible defaults."""
        import uuid as _uuid

        log_dir = platformdirs.user_log_dir("open-voice-router")
        log_file_path = os.path.join(log_dir, "sessions.jsonl")

        # Pre-populate Deepgram if the API key is available in the environment
        default_stt: list[ProviderConfig] = []
        deepgram_key = os.environ.get("DEEPGRAM_API_KEY")
        if deepgram_key:
            default_stt = [
                ProviderConfig(
                    id=str(_uuid.uuid4()),
                    name="Deepgram",
                    base_url="https://api.deepgram.com",
                    model="nova-3",
                    quota_limit=None,
                    quota_used_today=0,
                )
            ]

        default_prompts = [
            PromptConfig(
                id=str(_uuid.uuid4()),
                name="General",
                text=DEFAULT_SYSTEM_PROMPT,
                is_active=True,
            ),
            PromptConfig(
                id=str(_uuid.uuid4()),
                name="Email",
                text=DEFAULT_EMAIL_PROMPT,
                is_active=False,
            ),
            PromptConfig(
                id=str(_uuid.uuid4()),
                name="Coding",
                text=DEFAULT_CODING_PROMPT,
                is_active=False,
            ),
        ]

        return AppSettings(
            active_mode="dictation",
            hotkey="ctrl+shift+space",
            microphone_device_id=None,
            stt_providers=default_stt,
            llm_providers=[],
            log_file_path=log_file_path,
            prompts=default_prompts,
            word_dictionary=list(DEFAULT_WORD_DICTIONARY),
        )


@dataclass
class FallbackRecord:
    """Records a single provider fallback event within a session."""

    original_provider_id: str
    reason: str
    fallback_provider_id: str


@dataclass
class SessionLogEntry:
    """Structured log entry for a single recording session."""

    session_id: str
    timestamp: str  # ISO 8601
    mode: str
    stt_provider_id: str
    stt_latency_ms: int
    stt_outcome: str  # "success" | error code
    llm_provider_id: str | None = None
    llm_latency_ms: int | None = None
    llm_outcome: str | None = None
    fallbacks: list[FallbackRecord] = field(default_factory=list)


@dataclass
class ProviderPreset:
    """A built-in preset that pre-fills provider configuration fields."""

    name: str
    base_url: str
    model: str
    provider_type: Literal["stt", "llm"]


